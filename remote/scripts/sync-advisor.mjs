// Copies the what_next prompt body from docs/ADVISOR.md into src/advisor.js.
// ADVISOR.md stays the single source (D13); the test fails when the copy is out of date.
// Usage: node scripts/sync-advisor.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../../', import.meta.url);
const target = new URL('../src/advisor.js', import.meta.url);

export function advisorSource() {
  const t = readFileSync(new URL('docs/ADVISOR.md', root), 'utf8');
  const a = t.indexOf('<!-- prompt:start -->'), b = t.indexOf('<!-- prompt:end -->');
  if (a < 0 || b <= a) throw new Error('prompt markers missing in docs/ADVISOR.md');
  const body = t.slice(a + '<!-- prompt:start -->'.length, b).trim();
  return '// Generated by scripts/sync-advisor.mjs from docs/ADVISOR.md. Do not edit by hand.\n' +
    `export const ADVISOR_PROMPT = ${JSON.stringify(body)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const want = advisorSource();
  if (process.argv.includes('--check')) {
    const have = readFileSync(target, 'utf8');
    if (have !== want) { console.error('src/advisor.js is out of date: run node scripts/sync-advisor.mjs'); process.exit(1); }
    console.log('src/advisor.js matches docs/ADVISOR.md');
  } else {
    writeFileSync(target, want);
    console.log('wrote src/advisor.js');
  }
}
